"""Backbone support beyond what the pinned Transformers release covers.

The repo is pinned to transformers 4.44 because every eviction hijack in
adaptive_snapkv / andpro_snapkv / causal_andpro_snapkv / causal_lookahead_snapkv
patches `*FlashAttention2.forward` and `*Model.forward`, classes that were
removed in 4.48 when attention moved behind `ALL_ATTENTION_FUNCTIONS`.

Two backbones need help under that pin, for different reasons:

    mistralai/Ministral-3-8B-Instruct-2512  ->  `ministral3`, added in
        transformers 5.x. Reaching it by upgrading would invalidate every hijack
        on the backbones already reported, so this package re-expresses the
        architecture in the 4.44 Llama idiom instead: modeling_ministral3.py
        subclasses `transformers.models.llama.modeling_llama`, exposing exactly
        the surface the hijacks patch and inheriting Llama's cache, mask and
        rotary plumbing unchanged.

    Qwen/Qwen2.5-*-Instruct  ->  `qwen2`, native to 4.44 and needing no vendoring
        at all. Its 4.44 implementation predates the rotary refactor, though --
        no `position_embeddings`, a table-based rotary indexed by `position_ids`
        -- so it still needs its own hijack forwards. Those are generated by
        scripts/gen_ext_hijacks.py and wired up through hijack_targets.py.

Correctness is not assumed: scripts/validate_models_ext.py loads the same
checkpoint under upstream transformers 5.x in a separate venv and asserts the
logits agree. See README.md in this directory for the recorded results.
"""

# models_ext vendors Ministral-3 as a subclass of transformers 4.44's Llama modules
# (it needs LlamaFlashAttention2, which 4.48 deleted). That makes the package
# unimportable on the transformers 5.x venv used by the hybrid-attention backbones
# -- and every experiments/*/pred.py imports it unconditionally, so an unguarded
# ImportError there kills runs that never wanted Ministral-3 in the first place.
#
# On 5.x, registration degrades to a no-op: the extra architectures it registers are
# 4.44-only backbones, and the 5.x-native ones (qwen3_5, gemma4_unified) are already
# known to AutoConfig without any help. The reason is recorded on the function so a
# caller can tell "registered nothing because nothing was needed" from "silently
# broken".
try:
    from models_ext.register import register_extra_architectures
    register_extra_architectures.unavailable_reason = None
except ImportError as _exc:                      # transformers 5.x: no LlamaFlashAttention2
    _reason = str(_exc)

    def register_extra_architectures():          # type: ignore[misc]
        """No-op: the vendored 4.44-only architectures cannot load on this stack."""
        return None

    register_extra_architectures.unavailable_reason = _reason

__all__ = ["register_extra_architectures"]
